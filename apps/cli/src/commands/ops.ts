import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { Command } from 'commander';
import pc from 'picocolors';
import { connectDatabase, migrateDown, migrateToLatest, migrationStatus, redactUrl } from '@morrow/db';
import { checkDomainDns, ConfigError, createEngine, loadConfig, MORROW_VERSION, seedDemo, type Engine } from '@morrow/engine';
import { handleSignals, startRuntime, type RuntimeRole } from '@morrow/server';
import { CliError, type CliContext } from '../context';
import { formatDate } from '../output';

type Action = (ctx: CliContext, ...args: any[]) => Promise<void>;
export type Register = (program: Command, run: (action: Action) => (...args: any[]) => Promise<void>) => void;

const dbUrl = (ctx: CliContext, flag?: string) => flag ?? ctx.env.DATABASE_URL ?? 'sqlite:./data/morrow.db';

async function withEngine<T>(ctx: CliContext, flag: string | undefined, fn: (engine: Engine) => Promise<T>): Promise<T> {
  const engine = await createEngine({ databaseUrl: dbUrl(ctx, flag), migrate: false });
  try {
    return await fn(engine);
  } finally {
    await engine.close();
  }
}

function strongPassword(): string {
  return randomBytes(18).toString('base64url');
}

export function envTemplate(options: { secret: string; databaseUrl: string; publicUrl: string; port: number }): string {
  return `# Morrow configuration — generated by \`morrow init\`.
# Keep this file private. Never commit it.

MORROW_ENV=development
PORT=${options.port}
# Public base URL used in e-mails (unsubscribe, tracking, verification). Must be https:// in production.
MORROW_PUBLIC_URL=${options.publicUrl}
# Master secret for encrypting provider credentials and signing links. Changing it invalidates links and stored secrets.
MORROW_SECRET_KEY=${options.secret}

# sqlite:./data/morrow.db for a single machine, or postgres://user:pass@host:5432/morrow
DATABASE_URL=${options.databaseUrl}

# E-mail delivery: fake (development inbox, nothing leaves the machine), smtp, resend or postmark.
MORROW_EMAIL_PROVIDER=fake
# MORROW_SYSTEM_FROM_EMAIL=no-reply@example.com
# SMTP_HOST=
# SMTP_PORT=587
# SMTP_USERNAME=
# SMTP_PASSWORD=
# RESEND_API_KEY=
# RESEND_WEBHOOK_SECRET=
# POSTMARK_SERVER_TOKEN=

# Optional AI writing assistance (drafts only). Leave unset to disable.
# MORROW_AI_PROVIDER=anthropic
# ANTHROPIC_API_KEY=

# MORROW_ALLOW_SIGNUP=false
# MORROW_METRICS_TOKEN=
# MORROW_TRUST_PROXY=false
`;
}

/** Commands that operate an installation directly (database access, no API). */
export const registerOps: Register = (program, run) => {
  program
    .command('init')
    .description('create a .env with a fresh secret key and prepare the database')
    .option('--force', 'overwrite an existing .env')
    .option('--database <url>', 'database URL', 'sqlite:./data/morrow.db')
    .option('--public-url <url>', 'public base URL', 'http://localhost:4400')
    .option('--port <port>', 'HTTP port', '4400')
    .option('--no-migrate', 'skip running migrations')
    .action(
      run(async (ctx, opts: { force?: boolean; database: string; publicUrl: string; port: string; migrate: boolean }) => {
        const path = resolve('.env');
        if (existsSync(path) && !opts.force) throw new CliError('.env already exists. Use --force to replace it (this rotates the secret key).');
        const secret = randomBytes(32).toString('base64url');
        writeFileSync(path, envTemplate({ secret, databaseUrl: opts.database, publicUrl: opts.publicUrl, port: Number(opts.port) }), { mode: 0o600 });
        if (opts.database.startsWith('sqlite:') || opts.database.startsWith('file:')) mkdirSync(resolve('data'), { recursive: true });
        let applied: string[] = [];
        if (opts.migrate) {
          const db = await connectDatabase(opts.database);
          try {
            applied = (await migrateToLatest(db.db)).applied;
          } finally {
            await db.close();
          }
        }
        ctx.output.result({ envFile: path, migrations: applied }, () => {
          ctx.output.success(`Wrote ${path} with a new secret key`);
          if (opts.migrate) ctx.output.success(`Database ready (${applied.length} migration${applied.length === 1 ? '' : 's'} applied)`);
          ctx.output.line(`\nNext:\n  ${pc.cyan('morrow seed --demo')}   load a demo workspace\n  ${pc.cyan('morrow start')}         run the server, worker and scheduler`);
        });
      }),
    );

  program
    .command('migrate')
    .description('apply pending database migrations')
    .option('--status', 'list migrations without applying them')
    .option('--down', 'roll back the latest migration (development only)')
    .option('--database <url>', 'database URL (default: DATABASE_URL)')
    .action(
      run(async (ctx, opts: { status?: boolean; down?: boolean; database?: string }) => {
        const url = dbUrl(ctx, opts.database);
        const db = await connectDatabase(url);
        try {
          if (opts.status) {
            const list = await migrationStatus(db.db);
            ctx.output.result(list, () =>
              ctx.output.table(list, [
                { label: 'Migration', value: (m) => m.name },
                { label: 'Applied', value: (m) => (m.executedAt ? formatDate(m.executedAt.toISOString()) : pc.yellow('pending')) },
              ]),
            );
            return;
          }
          if (opts.down) {
            if (loadConfig(ctx.env).env === 'production') throw new CliError('Refusing to roll back migrations in production.');
            const r = await migrateDown(db.db);
            ctx.output.result(r, () => ctx.output.success(`Rolled back ${r.applied.join(', ') || 'nothing'}`));
            return;
          }
          const r = await migrateToLatest(db.db);
          ctx.output.result({ database: redactUrl(url), applied: r.applied }, () =>
            ctx.output.success(r.applied.length ? `Applied ${r.applied.join(', ')}` : `Database is up to date (${redactUrl(url)})`),
          );
        } finally {
          await db.close();
        }
      }),
    );

  program
    .command('seed')
    .description('load demo data (example.com addresses only; nothing is sent)')
    .requiredOption('--demo', 'create the demo workspace')
    .option('--email <email>', 'demo owner e-mail', 'demo@morrow.local')
    .option('--password <password>', 'demo owner password')
    .option('--database <url>', 'database URL (default: DATABASE_URL)')
    .action(
      run(async (ctx, opts: { email: string; password?: string; database?: string }) => {
        const engine = await createEngine({ databaseUrl: dbUrl(ctx, opts.database) });
        try {
          const result = await seedDemo(engine, { email: opts.email, password: opts.password });
          ctx.output.result(result, () => {
            if (!result.created) {
              ctx.output.info(`The demo account ${result.email} already exists; nothing changed.`);
              return;
            }
            ctx.output.success(`Demo workspace created with ${result.contacts} contacts`);
            ctx.output.fields([
              ['Sign in at', engine.config.appUrl],
              ['E-mail', result.email],
              ['Password', result.password],
            ]);
          });
        } finally {
          await engine.close();
        }
      }),
    );

  const startCommand = (name: string, description: string, roles: RuntimeRole[] | null) =>
    program
      .command(name)
      .description(description)
      .option('--port <port>', 'HTTP port (default: PORT or 4400)')
      .option('--host <host>', 'bind address', '0.0.0.0')
      .option('--roles <list>', 'comma-separated: server,worker,scheduler')
      .option('--database <url>', 'database URL (default: DATABASE_URL)')
      .option('--no-web', 'serve the API without the web app')
      .action(
        run(async (ctx, opts: { port?: string; host: string; roles?: string; database?: string; web: boolean }) => {
          const picked = (opts.roles ? opts.roles.split(',').map((r) => r.trim()) : roles ?? ['server', 'worker', 'scheduler']) as RuntimeRole[];
          const engine = await createEngine({ databaseUrl: dbUrl(ctx, opts.database) });
          const runtime = await startRuntime({ engine, roles: picked, port: opts.port ? Number(opts.port) : undefined, host: opts.host, webDist: opts.web ? undefined : null });
          handleSignals({ ...runtime, stop: async () => { await runtime.stop(); await engine.close(); } });
          ctx.output.result({ url: runtime.url, roles: picked, version: MORROW_VERSION }, () => {
            ctx.output.success(`Morrow ${MORROW_VERSION} running: ${picked.join(', ')}`);
            if (runtime.url) ctx.output.line(`  ${pc.cyan(runtime.url)}  (public URL ${engine.config.publicUrl})`);
            ctx.output.line(pc.dim('  Press Ctrl+C to stop.'));
          });
          await new Promise(() => undefined); // keep running until a signal arrives
        }),
      );
  startCommand('start', 'run the server, worker and scheduler in one process', null);
  startCommand('server', 'run only the HTTP server', ['server']);
  startCommand('worker', 'run only a background worker', ['worker']);
  startCommand('scheduler', 'run only the scheduler (one per installation is enough; extras stand by)', ['scheduler']);

  const user = program.command('user').description('manage accounts directly in the database');
  user
    .command('create')
    .description('create an account, optionally with its own workspace')
    .requiredOption('--email <email>')
    .requiredOption('--name <name>')
    .option('--password <password>', 'initial password (generated when omitted)')
    .option('--workspace <name>', 'also create a workspace owned by this user')
    .option('--timezone <tz>', 'workspace time zone', 'UTC')
    .option('--database <url>')
    .action(
      run(async (ctx, opts: { email: string; name: string; password?: string; workspace?: string; timezone: string; database?: string }) => {
        const password = opts.password ?? strongPassword();
        const result = await withEngine(ctx, opts.database, async (engine) => {
          const u = await engine.auth.createUser({ email: opts.email, name: opts.name, password });
          const ws = opts.workspace ? await engine.workspaces.create(u, { name: opts.workspace, timezone: opts.timezone }) : null;
          return { userId: u.id, email: u.email, workspaceId: ws?.id ?? null };
        });
        ctx.output.result({ ...result, password: opts.password ? undefined : password }, () => {
          ctx.output.success(`Created ${result.email}${result.workspaceId ? ` with workspace "${opts.workspace}"` : ''}`);
          if (!opts.password) ctx.output.fields([['Password', password], ['', pc.dim('Shown once. Ask them to change it after signing in.')]]);
        });
      }),
    );
  user
    .command('reset-password')
    .description('set a new password and sign the user out everywhere')
    .requiredOption('--email <email>')
    .option('--password <password>', 'new password (generated when omitted)')
    .option('--database <url>')
    .action(
      run(async (ctx, opts: { email: string; password?: string; database?: string }) => {
        const password = opts.password ?? strongPassword();
        await withEngine(ctx, opts.database, (engine) => engine.auth.adminResetPassword(opts.email, password));
        ctx.output.result({ email: opts.email, password: opts.password ? undefined : password }, () => {
          ctx.output.success(`Password reset for ${opts.email}; existing sessions ended`);
          if (!opts.password) ctx.output.fields([['New password', password]]);
        });
      }),
    );

  program
    .command('doctor')
    .description('check configuration, database, migrations, queue and scheduler')
    .option('--database <url>')
    .action(
      run(async (ctx, opts: { database?: string }) => {
        const checks: Array<{ check: string; status: 'ok' | 'warn' | 'fail'; detail: string }> = [];
        const add = (check: string, status: 'ok' | 'warn' | 'fail', detail: string) => checks.push({ check, status, detail });
        const [major, minor] = process.versions.node.split('.').map(Number) as [number, number];
        add('Node.js', major > 22 || (major === 22 && minor >= 12) ? 'ok' : 'fail', `v${process.versions.node} (22.12+ required)`);
        let config: ReturnType<typeof loadConfig> | null = null;
        try {
          config = loadConfig(ctx.env);
          add('Configuration', 'ok', `${config.env} environment, public URL ${config.publicUrl}`);
          if (config.env !== 'production' && !ctx.env.MORROW_SECRET_KEY) add('Secret key', 'warn', 'Using the development secret. Run `morrow init` before going live.');
          else add('Secret key', 'ok', 'set');
          add('E-mail provider', config.defaultEmail ? (config.defaultEmail.provider === 'fake' ? 'warn' : 'ok') : 'warn', config.defaultEmail ? (config.defaultEmail.provider === 'fake' ? 'development inbox — nothing is delivered' : config.defaultEmail.provider) : 'none at installation level (workspaces can add their own)');
          add('System sender', config.systemFrom ? 'ok' : 'warn', config.systemFrom ? config.systemFrom.email : 'MORROW_SYSTEM_FROM_EMAIL not set; invitations use a workspace sender');
        } catch (err) {
          add('Configuration', 'fail', err instanceof ConfigError ? err.message : (err as Error).message);
        }
        const url = dbUrl(ctx, opts.database);
        try {
          const db = await connectDatabase(url);
          try {
            const status = await migrationStatus(db.db);
            const pending = status.filter((m) => !m.executedAt).length;
            add('Database', 'ok', `${db.dialect} ${redactUrl(url)}`);
            add('Migrations', pending ? 'fail' : 'ok', pending ? `${pending} pending — run \`morrow migrate\`` : `${status.length} applied`);
            if (!pending && config) {
              const engine = await createEngine({ database: db, migrate: false, config });
              const h = await engine.system.health();
              add('Queue', h.queue.lagSeconds > 300 ? 'warn' : 'ok', `lag ${h.queue.lagSeconds}s, ${h.queue.byStatus.dead ?? 0} dead, ${h.queue.runningExpired} stuck`);
              add('Scheduler', h.scheduler.healthy ? 'ok' : 'warn', h.scheduler.lastTickAt ? `last tick ${h.scheduler.secondsSinceTick}s ago` : 'has not run yet — start it with `morrow start` or `morrow scheduler`');
            }
          } finally {
            await db.close();
          }
        } catch (err) {
          add('Database', 'fail', `${redactUrl(url)}: ${(err as Error).message}`);
        }
        const failed = checks.some((c) => c.status === 'fail');
        ctx.output.result({ ok: !failed, checks }, () => {
          const icon = { ok: pc.green('✔'), warn: pc.yellow('⚠'), fail: pc.red('✖') };
          for (const c of checks) ctx.output.line(`${icon[c.status]} ${pc.bold(c.check.padEnd(16))} ${c.detail}`);
        });
        if (failed) throw new CliError('Some checks failed.', 1);
      }),
    );

  const dns = program.command('dns').description('deliverability checks');
  dns
    .command('check <domain>')
    .description('check SPF, DKIM, DMARC and MX records for a sending domain')
    .option('--selector <name...>', 'DKIM selectors to look for')
    .action(
      run(async (ctx, domain: string, opts: { selector?: string[] }) => {
        const result = await checkDomainDns(domain, opts.selector);
        const rows = [
          { check: 'MX', ...result.mx },
          { check: 'SPF', ...result.spf },
          { check: 'DMARC', ...result.dmarc },
          ...result.dkim.map((d) => ({ check: `DKIM (${d.selector})`, ...d })),
        ];
        ctx.output.result(result, () => {
          ctx.output.heading(`DNS for ${result.domain}`);
          ctx.output.table(rows, [
            { label: 'Check', value: (r) => r.check },
            { label: 'Status', value: (r) => (r.status === 'pass' ? pc.green(r.status) : r.status === 'fail' ? pc.red(r.status) : pc.yellow(r.status)) },
            { label: 'Detail', value: (r) => r.message, max: 70 },
            { label: 'Record', value: (r) => r.record, max: 50 },
          ]);
        });
      }),
    );
};
